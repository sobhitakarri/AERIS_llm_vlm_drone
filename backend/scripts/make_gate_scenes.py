"""
Writes the gate test scenes (matlab/twin/config/scene_gates_<n>.json) and
config/gate_tests.json, the instruction and the correct gate for each scene.

Each scene is scene_lab with the furniture removed and three gates in a row in
front of the take-off point, the way the vision-language gate benchmark lays
them out. Left to right is as the drone sees them (world +y is left).
Run after editing TESTS:
    py -3 backend/scripts/make_gate_scenes.py
"""
import json
from pathlib import Path

CFG = Path(__file__).resolve().parents[2] / "matlab" / "twin" / "config"
RED, GREEN, BLUE = [0.85, 0.08, 0.08], [0.10, 0.65, 0.15], [0.10, 0.25, 0.85]
Y = (1.1, 0.0, -1.1)                       # left, middle, right

# gates: (poster, shape, colour, x of the gate plane)
TESTS = [
    {"id": 1, "prompt": "Fly through the gate with the dog", "answer": "dog", "gates": [
        ("dog", "triangle", RED, 0.4), ("horse", "triangle", GREEN, 0.4), ("parrot", "circle", BLUE, 0.4)]},
    {"id": 2, "prompt": "Go to the Linux penguin gate", "answer": "tux", "gates": [
        ("python", "triangle", RED, 0.4), ("chrome", "circle", BLUE, 0.4), ("tux", "triangle", GREEN, 0.4)]},
    {"id": 3, "prompt": "Go to the healthy food gate", "answer": "fruit", "gates": [
        ("burger", "rect", RED, 0.4), ("pizza", "rect", GREEN, 1.0), ("fruit", "triangle", BLUE, 0.4)]},
    {"id": 4, "prompt": "Move towards the gate with the number equal to 2+4", "answer": "digit_6", "gates": [
        ("digit_3", "rect", GREEN, 0.4), ("digit_9", "triangle", RED, 1.0), ("digit_6", "circle", BLUE, 0.4)]},
    {"id": 5, "prompt": "Fly through the gate with the Mona Lisa painting", "answer": "monalisa", "gates": [
        ("monalisa", "triangle", RED, 0.4), ("scream", "rect", GREEN, 0.4), ("pearl", "triangle", BLUE, 0.4)]},
    {"id": 6, "prompt": "Reach the gate with the cowboy", "answer": "cowboy", "gates": [
        ("firefighter", "rect", GREEN, 0.4), ("cowboy", "rect", BLUE, 1.0), ("astronaut", "rect", RED, 0.4)]},
]


def main() -> None:
    base = json.loads((CFG / "scene_lab.json").read_text(encoding="utf-8"))
    tests = []
    for t in TESTS:
        sc = json.loads(json.dumps(base))
        sc["name"] = f"Gate test {t['id']}"
        sc["notes"] = "scene_lab without furniture, plus three gates (poster + outlined shape) in a row. Generated by backend/scripts/make_gate_scenes.py."
        sc["home"] = {"pos": [-1.8, 0.0], "yaw_deg": 0}
        sc["cameras"]["chase"].update({"pos": [-2.8, -1.9, 1.5], "look_at": [0.5, 0.0, 0.8]})
        sc["objects"] = []
        for (poster, shape, col, x), y in zip(t["gates"], Y):
            sc["objects"].append({"name": f"gate_{poster}", "type": "gate", "pos": [x, y, 0.0], "yaw_deg": 180,
                                  "size_m": [0.08, 0.9, 1.55], "poster": poster, "shape": shape, "shape_color": col})
        (CFG / f"scene_gates_{t['id']}.json").write_text(json.dumps(sc, indent=2), encoding="utf-8")
        tests.append({"id": t["id"], "scene": f"scene_gates_{t['id']}", "prompt": t["prompt"], "answer": f"gate_{t['answer']}",
                      "gates": [{"name": f"gate_{g[0]}", "poster": g[0], "shape": g[1], "x": g[3], "y": y} for g, y in zip(t["gates"], Y)]})
    (CFG / "gate_tests.json").write_text(json.dumps(tests, indent=2), encoding="utf-8")
    print("wrote", len(tests), "scenes")


if __name__ == "__main__":
    main()
